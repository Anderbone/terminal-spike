package com.yanjiyu.terminalspike.ui.guide

import androidx.annotation.StringRes
import com.yanjiyu.terminalspike.R

/** Optional detailed reference, reached separately from the concise visual lessons. */
internal enum class GuideReferenceTopic(
    @StringRes val label: Int,
    @StringRes val summary: Int,
    val tips: List<Int>,
    val codeSamples: Set<Int> = emptySet(),
    val commandSamples: Set<Int> = emptySet(),
    val links: List<Pair<Int, String>> = emptyList(),
    @StringRes val agentInstructions: Int? = null,
) {
    TAILSCALE(R.string.guide_reference_tailscale, R.string.guide_reference_tailscale_summary,
        listOf(R.string.guide_tailscale_computer, R.string.guide_tailscale_phone,
            R.string.guide_tailscale_ssh),
        links = listOf(R.string.guide_tailscale_download to "https://tailscale.com/download")),
    CODE_SERVER(R.string.guide_reference_code_server, R.string.guide_reference_code_server_summary,
        listOf(R.string.guide_code_server_computer, R.string.guide_code_server_start,
            R.string.guide_code_server_serve_intro, R.string.guide_code_server_serve,
            R.string.guide_code_server_phone, R.string.guide_code_server_tabs,
            R.string.guide_code_server_troubleshooting),
        commandSamples = setOf(R.string.guide_code_server_serve),
        links = listOf(R.string.guide_code_server_install to "https://coder.com/docs/code-server/install",
            R.string.guide_tailscale_serve_docs to "https://tailscale.com/docs/reference/tailscale-cli/serve")),
    ATTACHMENTS(R.string.guide_reference_attachments, R.string.guide_reference_attachments_summary,
        listOf(R.string.guide_attachment_photos, R.string.guide_attachment_files,
            R.string.guide_attachment_clipboard, R.string.guide_attachment_destination,
            R.string.guide_attachment_formats)),
    DRAFTS(R.string.guide_reference_drafts, R.string.guide_reference_drafts_summary,
        listOf(R.string.guide_draft_pages, R.string.guide_draft_send, R.string.guide_draft_enter,
            R.string.guide_draft_undo, R.string.guide_draft_sessions, R.string.guide_draft_voice,
            R.string.guide_draft_snippets)),
    KEYS(R.string.guide_reference_keys, R.string.guide_reference_keys_summary,
        listOf(R.string.guide_keys_modifiers, R.string.guide_keys_lock, R.string.guide_keys_repeat,
            R.string.guide_keys_customize)),
    TERMINAL_TEXT(R.string.guide_reference_terminal, R.string.guide_reference_terminal_summary,
        listOf(R.string.guide_terminal_selection, R.string.guide_terminal_links,
            R.string.guide_terminal_mouse_keyboard, R.string.guide_terminal_zoom)),
    SESSIONS(R.string.guide_reference_sessions, R.string.guide_reference_sessions_summary,
        listOf(R.string.guide_sessions_duplicate, R.string.guide_sessions_actions,
            R.string.guide_sessions_switchers, R.string.guide_sessions_tmux, R.string.guide_sessions_focus)),
    HERDR(R.string.guide_reference_herdr, R.string.guide_reference_herdr_summary,
        listOf(R.string.guide_herdr_location, R.string.guide_herdr_merge,
            R.string.guide_herdr_basic_config, R.string.guide_herdr_layout,
            R.string.guide_herdr_compact, R.string.guide_herdr_compatibility,
            R.string.guide_herdr_grouped_config, R.string.guide_herdr_status,
            R.string.guide_herdr_git, R.string.guide_herdr_apply,
            R.string.guide_herdr_reattach, R.string.guide_herdr_agent_intro,
            R.string.guide_herdr_agent_prompt),
        codeSamples = setOf(R.string.guide_herdr_basic_config, R.string.guide_herdr_grouped_config),
        agentInstructions = R.string.guide_herdr_agent_prompt),
    FILES(R.string.guide_reference_files, R.string.guide_reference_files_summary,
        listOf(R.string.guide_files_open, R.string.guide_files_select, R.string.guide_files_move,
            R.string.guide_files_upload, R.string.guide_files_download, R.string.guide_files_refresh)),
}
